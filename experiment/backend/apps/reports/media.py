"""Photographs and documents inside the report.

The stored context (and so every report's input snapshot) holds only *which*
files go in, by storage key. The images themselves are read and inlined here
at render time, from files the app never overwrites or removes, so an issued
report re-renders with exactly the pictures it was signed with.

Everything is shrunk for the page first; the originals on disk stay as uploaded.
"""

from __future__ import annotations

import base64

from django.core.files.storage import default_storage

from apps.media_files import processing

PHOTO_EDGE = 1400
DOCUMENT_IMAGE_EDGE = 1600
# A 40-page contract does not belong in the report whole; the cap is stated on the page.
DOCUMENT_MAX_PAGES = 10


def _read(key: str) -> bytes | None:
    # Keys are generated by the app under jobs/; anything else is not ours to read.
    if not key.startswith("jobs/") or not default_storage.exists(key):
        return None
    with default_storage.open(key) as handle:
        return handle.read()


def _data_uri(jpeg: bytes) -> str:
    return "data:image/jpeg;base64," + base64.b64encode(jpeg).decode("ascii")


def resolve_media(context: dict) -> dict:
    """A copy of `context` with the images inlined as `src` (photographs) and
    `pages` (documents). A missing file gives an empty `src`; the template
    shows a marker, and issuing is blocked on it (see issue.py)."""
    cache: dict[str, str] = {}

    def photo_src(key: str) -> str:
        if key not in cache:
            data = _read(key)
            cache[key] = _data_uri(processing.downscale_jpeg(data, PHOTO_EDGE)) if data else ""
        return cache[key]

    def document(entry: dict) -> dict:
        data = _read(entry["key"])
        if data is None:
            pages, total = [], entry.get("page_count", 1)
        elif entry.get("kind") == "pdf":
            rendered, total = processing.render_pdf_pages(data, max_pages=DOCUMENT_MAX_PAGES)
            pages = [_data_uri(p) for p in rendered]
        else:
            pages, total = [_data_uri(processing.downscale_jpeg(data, DOCUMENT_IMAGE_EDGE))], 1
        # `src` (the first page) is what templates stored before documents had
        # several pages expect; keeping it means they still render.
        return {**entry, "pages": pages, "total_pages": total, "src": pages[0] if pages else ""}

    resolved = dict(context)
    resolved["photos"] = [{**p, "src": photo_src(p["key"])} for p in context.get("photos", [])]
    resolved["exec_photos"] = [{**p, "src": photo_src(p["key"])} for p in context.get("exec_photos", [])]
    resolved["documents"] = [document(d) for d in context.get("documents", [])]
    prop = context.get("property") or {}
    data = _read(prop["map"]) if prop.get("map") else None
    resolved["property"] = {
        **prop, "map_src": "data:image/jpeg;base64," + base64.b64encode(data).decode("ascii") if data else "",
    }
    resolved["document_max_pages"] = DOCUMENT_MAX_PAGES
    return resolved
